#!/usr/bin/env python3
"""
Generates target/pocket/dsp_hq48_gauss.sv from the S-DSP Gaussian interpolation
table in rtl/upstream/DSP_PKG.vhd, so the 48kHz renderer uses the exact same
table as the DSP.
"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..")
pkg = open(os.path.join(root, "rtl", "upstream", "DSP_PKG.vhd")).read()
body = pkg[pkg.index("constant  GTBL"):]
body = body[:body.index(");")]
vals = [int(v, 16) for v in re.findall(r'x"([0-9A-Fa-f]{3})"', body)]
assert len(vals) == 512, len(vals)
out = os.path.join(root, "target", "pocket", "dsp_hq48_gauss.sv")
with open(out, "w") as f:
    f.write("// AUTO-GENERATED by support/audio/gen_gauss_rom.py from DSP_PKG.vhd GTBL. Do not edit.\n")
    f.write("module dsp_hq48_gauss (\n    input wire clk,\n    input wire [8:0] addr,\n    output reg signed [11:0] q\n);\n")
    f.write("  always @(posedge clk) begin\n    case (addr)\n")
    for i, v in enumerate(vals):
        f.write(f"      9'd{i}: q <= 12'h{v:03X};\n")
    f.write("      default: q <= 12'h000;\n    endcase\n  end\nendmodule\n")
print("wrote", out)
